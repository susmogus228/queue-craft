// Browser QA function for Playwright code runner. Uses isolated installed Edge; screenshots stage in runner-allowed C: then copy to project outputs.
async (page) => {
 const browser=await page.context().browser().browserType().launch({channel:'msedge',headless:true});
 const checks=[], errors=[]; let p; const folder='./';
 const check=(ok,name,detail)=>{checks.push({name,passed:!!ok,detail}); if(!ok)throw new Error(name+': '+JSON.stringify(detail));};
 try {
  const ctx=await browser.newContext({viewport:{width:1536,height:1024},deviceScaleFactor:1,acceptDownloads:true});
  p=await ctx.newPage(); p.on('pageerror',e=>errors.push(e.message));
  await p.goto('http://127.0.0.1:8774/');
  await p.getByRole('button',{name:'Compare strategies',exact:true}).first().waitFor();
  const dimensions=await p.evaluate(()=>({width:innerWidth,height:innerHeight,scroll:document.documentElement.scrollWidth}));
  check(dimensions.width===1536 && dimensions.scroll<=1537,'Desktop viewport and no body overflow',dimensions);
  await p.waitForFunction(()=>document.querySelector('#example-select')?.options.length===3);
  check(await p.getByLabel('Problem',{exact:true}).locator('option').count()===3,'Three nonduplicated scenarios');
  const runUi=async()=>{
   const response=p.waitForResponse(r=>r.url().endsWith('/api/runs')&&r.request().method()==='POST');
   await p.getByRole('button',{name:'Compare strategies',exact:true}).first().click();
   const created=await (await response).json();
   await p.waitForFunction(()=>/completed ·/.test(document.body.innerText),null,{timeout:15000});
   return await (await p.request.get('http://127.0.0.1:8774/api/runs/'+created.id)).json();
  };
  const run=await runUi();
  check(run.results.length===5 && run.results.every(r=>r.validation.valid),'All five actual API schedules valid');
  check(run.results.find(r=>r.method==='cp_sat').makespan===11,'Small example proven reference 11');
  check(await p.getByRole('button',{name:'Export report',exact:true}).isEnabled(),'Completed export enabled');
  await p.getByRole('button',{name:/^CP-SAT/}).click();
  const cpInspector=await p.getByRole('complementary',{name:'Decision inspector'}).innerText();
  check(!cpInspector.includes('Dispatch trace') && await p.getByRole('button',{name:'Play replay'}).isDisabled(),'CP reference has no fake dispatch replay');
  await p.getByRole('button',{name:/^Learned policy/}).click();
  await p.getByRole('button',{name:'Previous decision'}).click();
  check((await p.getByRole('complementary',{name:'Decision inspector'}).innerText()).includes('step 7 of 8'),'Replay previous step');
  await p.getByRole('button',{name:'Play replay'}).click();
  await p.waitForFunction(()=>document.querySelector('#replay-step')?.value==='8',null,{timeout:3000});
  await p.getByRole('button',{name:/J1\.1: machine/}).focus();
  await p.keyboard.press('Enter');
  check(await p.getByLabel('Selected operation',{exact:true}).inputValue()==='J1.1','Gantt operation keyboard selection');
  await p.screenshot({path:folder+'queuecraft-desktop.png',fullPage:true});
  const downloadPromise=p.waitForEvent('download');
  await p.getByRole('button',{name:'Export report',exact:true}).click();
  const download=await downloadPromise;
  await download.saveAs(folder+'queuecraft-browser-export.json');
  const exported=await (await p.request.get('http://127.0.0.1:8774/api/runs/'+run.id+'/export')).json();
  check(exported.run.instance.name==='Small workshop','Export contains matching original instance');
  await p.getByLabel('Duration (time units)').fill('30');
  await p.getByRole('button',{name:'Apply change',exact:true}).click();
  check((await p.locator('body').innerText()).includes('previous input') || (await p.locator('body').innerText()).includes('Recompute'),'Edited result is marked stale');
  const modified=await runUi();
  check(modified.instance.jobs[0].operations[0].duration===30 && modified.results.every(r=>r.validation.valid),'Edit triggers real recomputation');
  check(modified.results.find(r=>r.method==='learned').makespan>run.results.find(r=>r.method==='learned').makespan,'Recomputation is not cached old schedule');
  await p.getByLabel('Import a JSON problem').setInputFiles({name:'exported-report.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(exported))});
  await p.waitForFunction(()=>document.querySelector('#duration')?.value==='3' && document.body.innerText.includes('Imported'));
  check(true,'Own exported report roundtrip');
  await p.getByLabel('Import a JSON problem').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{')});
  await p.getByRole('alert').filter({hasText:'valid JSON'}).waitFor(); check(true,'Malformed JSON shows actionable error');
  const duplicate=JSON.stringify(exported.run.instance).replace('"duration":3','"duration":1,"duration":3');
  await p.getByLabel('Import a JSON problem').setInputFiles({name:'ambiguous.json',mimeType:'application/json',buffer:Buffer.from(duplicate)});
  await p.getByRole('alert').filter({hasText:'Duplicate'}).waitFor(); check(true,'Ambiguous JSON rejected in UI');
  await p.getByLabel('Import a JSON problem').setInputFiles({name:'large.json',mimeType:'application/json',buffer:Buffer.alloc(131073,32)});
  await p.getByRole('alert').filter({hasText:'128 KiB'}).waitFor(); check(true,'Oversized file rejected without upload');
  await p.getByRole('button',{name:'Dismiss error'}).click();
  await p.getByRole('button',{name:'Research',exact:true}).click();
  const research=await p.locator('body').innerText();
  check(research.includes('20.95%') && research.includes('10.06%') && research.includes('-0.91%'),'Actual model evidence rendered');
  check(research.includes('95%') && research.includes('FIFO') && research.includes('CP-SAT'),'Intervals and strong comparisons visible');
  await p.screenshot({path:folder+'queuecraft-research.png',fullPage:true});
  await p.getByRole('button',{name:'Plan',exact:true}).click();
  let seed=919; const random=()=>{seed=(seed*1664525+1013904223)>>>0;return seed/4294967296;};
  const large={name:'QA bounded workload',machines:12,jobs:Array.from({length:12},(_,j)=>{const order=Array.from({length:12},(_,i)=>i);for(let i=11;i>0;i--){const k=Math.floor(random()*(i+1));[order[i],order[k]]=[order[k],order[i]];}return{id:'Q'+j,operations:order.map(machine=>({machine,duration:1+Math.floor(random()*30)}))};})};
  await p.getByLabel('Import a JSON problem').setInputFiles({name:'workload.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(large))});
  await p.getByLabel('CP-SAT time limit (seconds)').fill('5');
  await p.getByRole('button',{name:'Compare strategies',exact:true}).first().click();
  await p.getByRole('button',{name:/Cancel/}).click();
  await p.waitForFunction(()=>/cancelled ·/.test(document.body.innerText),null,{timeout:10000});
  check(true,'UI cancellation completes with actual bounded service');
  await p.setViewportSize({width:390,height:844}); await p.reload();
  await p.getByRole('button',{name:'Compare strategies',exact:true}).first().waitFor();
  await runUi();
  const mobile=await p.evaluate(()=>({width:innerWidth,height:innerHeight,scroll:document.documentElement.scrollWidth}));
  check(mobile.width===390 && mobile.scroll<=391,'Mobile 390px has no body overflow',mobile);
  check(await p.getByRole('button',{name:'Export report',exact:true}).isEnabled(),'Mobile comparison and export accessible');
  await p.screenshot({path:folder+'queuecraft-mobile.png',fullPage:true});
  await p.emulateMedia({reducedMotion:'reduce'});
  await p.waitForFunction(()=>matchMedia('(prefers-reduced-motion: reduce)').matches);
  await p.waitForFunction(()=>document.querySelector('[aria-label="Play replay"]')?.disabled);
  check(true,'Reduced motion disables automatic replay');
  await p.getByRole('button',{name:'Previous decision'}).click();
  check((await p.getByRole('complementary',{name:'Decision inspector'}).innerText()).includes('step 7 of 8'),'Reduced motion retains manual stepping');
  await p.setViewportSize({width:320,height:740});
  check(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Narrow 320px no body overflow');
  await p.setViewportSize({width:1024,height:768});
  check(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Tablet 1024px no body overflow');
  await p.route('**/api/examples',route=>route.fulfill({status:503,contentType:'application/json',body:'{"detail":"Temporary example service failure"}'}));
  await p.reload(); await p.getByRole('button',{name:'Retry connection'}).waitFor();
  check((await p.getByRole('alert').innerText()).includes('Temporary example'),'Unavailable API state has retry');
  await p.unroute('**/api/examples');
  await p.getByRole('button',{name:'Retry connection'}).click();
  await p.waitForFunction(()=>document.querySelector('#example-select')?.options.length===3);
  check(await p.getByRole('button',{name:'Compare strategies',exact:true}).first().isEnabled(),'API retry recovers without reload');
  check(errors.length===0,'No uncaught browser exceptions',errors);
  return {passed:true,checks,errors};
 } catch(error) { if(p)await p.screenshot({path:folder+'queuecraft-qa-failure.png',fullPage:true}); return {passed:false,error:String(error),checks,errors}; }
 finally {await browser.close();}
}

